package For_Loops;

public class BasicForLoop {

	public static void main(String[] args) {
		// For Loops
		// Basic Syntax
		/* for (initialization; condition; increment/decrement;) {
		 * 		Statement
		 * }
		 * */
		
		for (int i = 1; i <= 5; i++) {
			System.out.println("Number: " + i);
		}
		
	} // main method
}// class
